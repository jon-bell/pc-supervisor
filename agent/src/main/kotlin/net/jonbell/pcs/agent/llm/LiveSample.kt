package net.jonbell.pcs.agent.llm

import kotlinx.coroutines.runBlocking
import net.jonbell.pcs.agent.engines.Adapter
import net.jonbell.pcs.agent.engines.CallRequest
import net.jonbell.pcs.agent.engines.CallResult
import net.jonbell.pcs.agent.engines.Caps
import net.jonbell.pcs.agent.engines.ClaudeCodeEngine
import net.jonbell.pcs.agent.engines.DataClass
import net.jonbell.pcs.agent.engines.Dispatcher
import net.jonbell.pcs.agent.engines.Engine
import net.jonbell.pcs.agent.engines.EngineConfig
import net.jonbell.pcs.agent.engines.FileResultStore
import net.jonbell.pcs.agent.engines.PaperInput
import net.jonbell.pcs.agent.engines.Registered
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardOpenOption

/**
 * The fixed sample of live calls and the fixtures recorded from it. Every paper is a [LlmCorpus] case,
 * generated by this project; nothing else is ever sent. [PLAN] says which checks run on which case, so the
 * recording run and the replay tests make exactly the same requests (and so have the same keys).
 */
object LiveSample {
    /** The engine identity the fixtures are recorded under: tests replay `dev` with this model. */
    const val ENGINE = "dev"
    const val MODEL = "haiku"

    /** case id to the checks that run on it. */
    val PLAN: List<Pair<String, List<String>>> =
        listOf(
            "summary/clean" to listOf("summary"),
            "anonymity-llm/clean" to listOf("anonymity.llm"),
            "anonymity-llm/own-prior-work" to listOf("anonymity.llm"),
            "anonymity-llm/identifying-link" to listOf("anonymity.llm"),
            "scope/in-scope" to listOf("scope"),
            "scope/domain-swap" to listOf("scope"),
            "refs-use/faithful" to listOf("refs.use"),
            "refs-use/miscited" to listOf("refs.use"),
            "injection-addressed-llm/attack" to listOf("injection.addressed.llm"),
            "injection-addressed-llm/quotation" to listOf("injection.addressed.llm"),
            "injection-effect/obeyed" to listOf("summary"),
        )

    fun env(c: LlmCase) = CheckEnv(LlmCorpus.CFP, AbstractSource.fixed(c.abstracts))

    fun paper(c: LlmCase, dataClass: DataClass = DataClass.SYNTHETIC) =
        PaperInput(
            c.id,
            dataClass,
            c.pdf,
            net.jonbell.pcs.agent.checks.ScreenConfig(authors = c.authors),
        )

    fun checksOf(all: List<ScreenLlmCheck>, ids: List<String>) = ids.map { id -> all.first { it.id == id } }

    /** The `dev` engine as configured for the live run: the Claude Code login, a public ceiling, a small model. */
    fun liveConfig(model: String = MODEL) = EngineConfig(ENGINE, Adapter.CLAUDE_CODE, model, DataClass.PUBLIC, null, concurrency = 1)

    /** Wraps an engine so that the run stops at a hard cap and every call is logged (no paper text in the log). */
    private class Capped(private val inner: Engine, private val log: Path, private var remaining: Int) : Engine {
        override val id get() = inner.id
        override val caps: Caps get() = inner.caps
        var made = 0

        override suspend fun call(req: CallRequest): CallResult {
            check(remaining > 0) { "live-call cap reached; stopping" }
            remaining--
            made++
            val r = inner.call(req).let { it.copy(raw = redact(it.raw)) }
            if (r.status !=
                net.jonbell.pcs.agent.engines.Status.OK
            ) {
                System.err.println("live call ${req.check.id}: ${r.status}: ${r.detail}; output starts: ${r.raw.take(300)}")
            }
            Files.writeString(
                log,
                "${req.check.id}@${req.check.version}\t${req.variant}\t${r.status}\t${r.servedModel}\tcost_usd=${r.costUsd}\tin=${r.usage.input}\tout=${r.usage.output}\n",
                StandardOpenOption.CREATE,
                StandardOpenOption.APPEND,
            )
            return r
        }
    }

    /** Drops the session and credential identifiers from the CLI envelope before it is kept as a fixture. Everything else, which the monitors read, stays. */
    internal fun redact(raw: String): String {
        val o = runCatching { kotlinx.serialization.json.Json.parseToJsonElement(raw) as? kotlinx.serialization.json.JsonObject }.getOrNull() ?: return raw
        return kotlinx.serialization.json.JsonObject(o.filterKeys { it !in setOf("session_id", "uuid", "credential_expires_at") }).toString()
    }

    /**
     * `LiveSampleKt <repo agent dir> <cap>`: records the sample through the `claude-code` adapter into
     * `fixtures/replay`. Calls already recorded are not repeated. Run by hand with `PCS_LIVE_OK=1`.
     */
    @JvmStatic
    fun main(args: Array<String>) {
        check(System.getenv("PCS_LIVE_OK") == "1") { "live calls are made only by hand: set PCS_LIVE_OK=1" }
        check(System.getProperty("pcs.noLive") != "true" && System.getenv("CI").isNullOrEmpty()) { "refusing to make live calls in a test or CI run" }
        val agentDir = Path.of(args[0])
        val cap = args[1].toInt()
        val only = args.getOrNull(2)
        val store = FileResultStore(agentDir.resolve("fixtures/replay"))
        val log = agentDir.resolve("fixtures/live-calls.log")
        val cfg = liveConfig()
        val engine = Capped(ClaudeCodeEngine(cfg), log, cap)
        val dispatcher = Dispatcher(listOf(Registered(cfg, engine)), store)
        val decisions = Decisions.load(agentDir.resolve("decisions.example.yaml"))
        val all = Screener.checks(agentDir.resolve("checks"))
        val cases = LlmCorpus.generate().associateBy { it.id }
        for ((caseId, checkIds) in PLAN) {
            if (only != null && only != caseId) continue
            val c = cases.getValue(caseId)
            val screener =
                Screener(
                    dispatcher,
                    checkIds.associateWith {
                        ENGINE
                    },
                    checksOf(all, checkIds),
                    decisions,
                    env(c),
                    Screener.deterministicDeps(agentDir.resolve("checks")),
                )
            val screen = runBlocking { screener.screen(paper(c)) }
            println(
                "$caseId: ${screen.calls.joinToString {
                    "${it.check}/${it.run}=${it.status}${if (it.cached) "(cached)" else ""}"
                }}; flags: ${screen.flags.filter {
                    it.check in checkIds || it.check == "injection.effect"
                }.joinToString { "${it.check}:${it.kind}:${it.status}" }}",
            )
        }
        println("live calls made in this run: ${engine.made}")
    }
}
